#!/usr/bin/env node
/**
 * 从 tree-sitter grammar 源码里抽取关键字，生成 internal/completion/keywords_gen.go。
 *
 * 为什么要有这个脚本：
 *   补全需要一份"关键字清单"，而这份清单的唯一可信来源是 grammar 本身。
 *   手抄 300 个关键字必然与 grammar 漂移（grammar 加了 `FOREACH`，补全里没有）。
 *   重复利用 scripts/generate-tm-grammars.mjs 的 kw() 抽取逻辑，
 *   保证高亮与补全用的是同一份清单。
 *
 * 用法：
 *   node scripts/generate-keywords.mjs            # 生成
 *   node scripts/generate-keywords.mjs --check    # 只校验是否最新（CI 用）
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const workspaceRoot = path.resolve(here, "..", "..");

const BDL_GRAMMAR = path.join(workspaceRoot, "tree-sitter-bdl");
const PER_GRAMMAR = path.join(workspaceRoot, "tree-sitter-per");
const OUT = path.resolve(here, "..", "internal", "completion", "keywords_gen.go");

/** 从一个 JS 文件里抽出所有 kw("...") 的字面量。 */
function collectKw(files) {
  const words = new Set();
  for (const file of files) {
    const src = fs.readFileSync(file, "utf8");
    for (const m of src.matchAll(/kw\(\s*["'`]([^"'`]+)["'`]/g)) {
      words.add(m[1].toUpperCase().replace(/\s+/g, " ").trim());
    }
  }
  return words;
}

/** BDL 关键字：grammar.js + rule/*.js。 */
function bdlKeywords() {
  const dir = path.join(BDL_GRAMMAR, "rule");
  const files = [path.join(BDL_GRAMMAR, "grammar.js")];
  for (const name of fs.readdirSync(dir).sort()) {
    if (name.endsWith(".js")) {
      files.push(path.join(dir, name));
    }
  }
  return collectKw(files);
}

/** .per 关键字：rule/keywords.js。 */
function perKeywords() {
  return collectKw([path.join(PER_GRAMMAR, "rule", "keywords.js")]);
}

/**
 * 排序：短的在前、同长按字母序。
 *
 * 补全列表按这个顺序展示时，单关键字（IF/WHILE/CALL）会排在多词短语
 * （`END IF`/`ON EVERY ROW`）之前，符合"先给最常用的"直觉。
 */
function sortKeywords(words) {
  return [...words].sort((a, b) => {
    if (a.length !== b.length) {
      return a.length - b.length;
    }
    return a < b ? -1 : a > b ? 1 : 0;
  });
}

/** 生成 Go 源码。 */
function render() {
  const bdl = sortKeywords(bdlKeywords());
  const per = sortKeywords(perKeywords());

  const fmt = (name, words, lang) => {
    const lines = [];
    lines.push(`// ${name} 是 ${lang} 的关键字（由 scripts/generate-keywords.mjs 生成，勿手改）。`);
    lines.push(`var ${name} = []string{`);
    // 每行 4 个，避免超长行难以 review。
    for (let i = 0; i < words.length; i += 4) {
      const chunk = words.slice(i, i + 4).map((w) => JSON.stringify(w));
      lines.push(`\t${chunk.join(", ")},`);
    }
    lines.push(`}`);
    return lines.join("\n");
  };

  return [
    "// Code generated by scripts/generate-keywords.mjs; DO NOT EDIT.",
    "",
    "package completion",
    "",
    fmt("BDLKeywords", bdl, "BDL（.4gl/.global）"),
    "",
    fmt("PERKeywords", per, ".per"),
    "",
  ].join("\n");
}

const want = render();

if (process.argv.includes("--check")) {
  const exists = fs.existsSync(OUT);
  const have = exists ? fs.readFileSync(OUT, "utf8") : "";
  if (have !== want) {
    console.error(
      `关键字清单已过期：${path.relative(workspaceRoot, OUT)}\n` +
        `请运行 node scripts/generate-keywords.mjs`,
    );
    process.exit(1);
  }
  console.log("关键字清单是最新的");
  process.exit(0);
}

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, want, "utf8");
const bdlCount = (want.match(/BDLKeywords/) ? bdlKeywords().size : 0);
console.log(
  `已生成 ${path.relative(workspaceRoot, OUT)}（BDL ${bdlCount} 个，PER ${perKeywords().size} 个）`,
);
